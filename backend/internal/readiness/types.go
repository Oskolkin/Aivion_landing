package readiness

import (
	"github.com/Oskolkin/marketplace-ai-mvp/backend/internal/factualapi"
	"time"
)

type Clock interface{ Now() time.Time }
type RealClock struct{}

func (RealClock) Now() time.Time { return time.Now().UTC() }

type SemanticRegistry interface {
	State(capability string) string
}
type ProductionSemanticRegistry struct{}

func (ProductionSemanticRegistry) State(string) string { return "PENDING_ACCEPTANCE" }

type StaticSemanticRegistry map[string]string

func (s StaticSemanticRegistry) State(k string) string {
	if v := s[k]; v != "" {
		return v
	}
	return "VALIDATED"
}

const (
	GateReady        = "READY"
	GateBlocked      = "BLOCKED"
	GateInsufficient = "INSUFFICIENT_ANALYSIS_HISTORY"
	GateEmpty        = "CONNECTED_NO_ANALYZABLE_DATA"
)

type DQIssue struct {
	Domain, Dimension, Code, Severity, ReadinessEffect, RetryClass string
	PeriodStart, PeriodEnd                                         *time.Time
	Details                                                        map[string]any
}
type Watermark struct {
	Domain, FactFamily                                                           string
	LatestObservedAt                                                             *time.Time
	LatestCompleteBusinessDate, LatestMatureBusinessDate, HistoryFrom, HistoryTo *time.Time
	LatestCompleteSnapshotAt                                                     *time.Time
	DomainRunID                                                                  *int64
	SourceContractHash, SemanticMappingHash, SourceRevisionHash, StateHash       string
	AssessedAt                                                                   time.Time
}
type Capability struct {
	ID                                                                                                                                                              int64
	Key, Scope, Domain, FinalState, ContractState, AccessState, SourceState, SemanticState, CoverageState, TemporalState, HistoryState, PopulationState, ReasonCode string
	Details                                                                                                                                                         map[string]any
	AssessedAt                                                                                                                                                      time.Time
	DomainRunID                                                                                                                                                     *int64
}
type Candidate struct {
	Date            *time.Time
	Status          string
	Selected        bool
	BlockingReasons []string
	EvaluationID    int64
}
type Result struct {
	SellerAccountID, DQRunID int64
	CutoffAt                 time.Time
	Policies                 factualapi.PolicyVersions
	InputHash, ResultHash    string
	Watermarks               []Watermark
	Capabilities             []Capability
	Issues                   []DQIssue
	Candidates               []Candidate
	AnalysisDate             *time.Time
	Context                  *factualapi.FactualReadContext
}

