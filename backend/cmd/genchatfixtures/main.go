func main() {
	outDir := filepath.Join("debug", "ai-chat-audit", "fixtures")
	_ = os.MkdirAll(outDir, 0o755)

	mustWrite(filepath.Join(outDir, "control.txt"), []byte("TXT_CONTROL_16735 — контрольное значение для аудита AI-чата Aivion.\n"))
	mustWrite(filepath.Join(outDir, "control.md"), []byte("# Отчёт\n\n## Раздел\n\nMD_CONTROL_53892\n\n| A | B |\n|---|---|\n| 1 | 2 |\n\n```\ncode\n```\n"))
	mustWrite(filepath.Join(outDir, "control.json"), []byte(`{"control":"JSON_CONTROL_62418","nested":{"value":731}}`+"\n"))

	var csv strings.Builder
	csv.WriteString("sku;товар;продажи;выручка\n")
	sum := 0
	maxV := 0
	for i := 1; i <= 50; i++ {
		v := i * 17
		sum += v
		if v > maxV {
			maxV = v
		}
		marker := ""
		if i == 25 {
			marker = "CSV_CONTROL_71934"
		}
		fmt.Fprintf(&csv, "8010001%04d;%s;%d;%d\n", i, marker, i, v)
	}
	fmt.Fprintf(&csv, "# meta sum=%d max=%d\n", sum, maxV)
	mustWrite(filepath.Join(outDir, "control.csv"), []byte(csv.String()))

	var tsv strings.Builder
	tsv.WriteString("sku\tmetric\tvalue\n")
	tsv.WriteString("1\tmarker\tTSV_CONTROL_88421\n")
	for i := 0; i < 20; i++ {
		fmt.Fprintf(&tsv, "%d\torders\t%d\n", i+2, i*3)
	}
	mustWrite(filepath.Join(outDir, "control.tsv"), []byte(tsv.String()))

	must(writeXLSX(filepath.Join(outDir, "control.xlsx")))
	must(writePDF(filepath.Join(outDir, "control.pdf")))
	must(writeDOCX(filepath.Join(outDir, "control.docx")))
	must(writePPTX(filepath.Join(outDir, "control.pptx")))
	must(writeImage(filepath.Join(outDir, "control.png"), "png", "PNG_CONTROL_55102"))
	must(writeImage(filepath.Join(outDir, "control.jpg"), "jpeg", "JPEG_CONTROL_66213"))
	// WebP is generated by scripts/gen_control_webp.mjs (sharp) — keep existing file if present.
	if _, err := os.Stat(filepath.Join(outDir, "control.webp")); err != nil {
		fmt.Println("warning: control.webp missing; run node scripts/gen_control_webp.mjs")
	}
	must(writeZIP(outDir, filepath.Join(outDir, "control.zip")))

	// Self-check extraction roundtrip for fixtures.
	report := map[string]any{}
	entries, _ := os.ReadDir(outDir)
	for _, e := range entries {
		if e.IsDir() {
			continue
		}
		name := e.Name()
		data, err := os.ReadFile(filepath.Join(outDir, name))
		if err != nil {
			continue
		}
		ext, err := chatextract.Extract(name, "", data)
		item := map[string]any{"bytes": len(data), "sha256": sha(data)}
		if err != nil {
			item["extract_error"] = err.Error()
		} else {
			item["format"] = ext.Format
			item["chars"] = len(ext.PlainText)
			item["plain_preview"] = trim(ext.PlainText, 160)
		}
		report[name] = item
	}
	raw, _ := json.MarshalIndent(report, "", "  ")
	mustWrite(filepath.Join(outDir, "fixture-extract-selfcheck.json"), raw)
	fmt.Println("fixtures ready in", outDir)
}

func writeXLSX(path string) error {
	f := excelize.NewFile()
	defer func() { _ = f.Close() }()
	_, _ = f.NewSheet("Сводка")
	_, _ = f.NewSheet("Продажи")
	_, _ = f.NewSheet("Контроль")
	_ = f.DeleteSheet("Sheet1")
	_ = f.SetCellValue("Сводка", "A1", "Показатель")
	_ = f.SetCellValue("Сводка", "B1", "Значение")
	_ = f.SetCellValue("Сводка", "A2", "Выручка")
	_ = f.SetCellValue("Сводка", "B2", 125000)
	_ = f.SetCellValue("Продажи", "D12", 48317)
	_ = f.SetCellValue("Продажи", "A1", "SKU")
	_ = f.SetCellValue("Контроль", "B7", "XLSX_CONTROL_51283")
	_ = f.SetCellFormula("Контроль", "C7", "10+5")
	return f.SaveAs(path)
}

