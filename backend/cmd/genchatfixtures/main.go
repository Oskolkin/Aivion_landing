func writeImage(path, kind, marker string) error {
	img := image.NewRGBA(image.Rect(0, 0, 640, 360))
	draw.Draw(img, img.Bounds(), &image.Uniform{C: color.RGBA{R: 245, G: 248, B: 255, A: 255}}, image.Point{}, draw.Src)
	drawLabel(img, 40, 60, "TITLE: Stock Report")
	drawLabel(img, 40, 100, "TABLE: SKU | Orders | Revenue")
	drawLabel(img, 40, 140, "801 | 12 | 48317")
	drawLabel(img, 40, 180, marker)
	drawLabel(img, 40, 220, "VALUE_ON_CHART=48317")
	var buf bytes.Buffer
	switch kind {
	case "png":
		if err := png.Encode(&buf, img); err != nil {
			return err
		}
		withText, err := chatextract.AppendPNGTExt(buf.Bytes(), "Control", marker)
		if err != nil {
			return err
		}
		return os.WriteFile(path, withText, 0o644)
	case "jpeg":
		if err := jpeg.Encode(&buf, img, &jpeg.Options{Quality: 92}); err != nil {
			return err
		}
		return os.WriteFile(path, injectJPEGComment(buf.Bytes(), marker), 0o644)
	default:
		return fmt.Errorf("unsupported image kind %s", kind)
	}
}

func injectJPEGComment(data []byte, comment string) []byte {
	if !bytes.HasPrefix(data, []byte{0xFF, 0xD8}) {
		return data
	}
	payload := []byte(comment)
	seg := make([]byte, 0, 4+len(payload))
	seg = append(seg, 0xFF, 0xFE)
	seg = append(seg, byte((len(payload)+2)>>8), byte((len(payload)+2)&0xff))
	seg = append(seg, payload...)
	out := make([]byte, 0, len(data)+len(seg))
	out = append(out, data[:2]...)
	out = append(out, seg...)
	out = append(out, data[2:]...)
	return out
}

func drawLabel(img *image.RGBA, x, y int, label string) {
	col := color.RGBA{R: 17, G: 24, B: 39, A: 255}
	point := fixed.Point26_6{X: fixed.I(x), Y: fixed.I(y)}
	d := &font.Drawer{Dst: img, Src: image.NewUniform(col), Face: basicfont.Face7x13, Dot: point}
	d.DrawString(label)
}

func writeZIP(fixtureDir, path string) error {
	files := []string{"control.pdf", "control.docx", "control.xlsx", "control.csv", "control.txt"}
	var buf bytes.Buffer
	zw := zip.NewWriter(&buf)
	manifest := map[string]string{}
	for _, name := range files {
		data, err := os.ReadFile(filepath.Join(fixtureDir, name))
		if err != nil {
			return err
		}
		w, err := zw.Create(name)
		if err != nil {
			return err
		}
		if _, err := w.Write(data); err != nil {
			return err
		}
		manifest[name] = sha(data)
	}
	raw, _ := json.MarshalIndent(manifest, "", "  ")
	mw, _ := zw.Create("manifest.json")
	_, _ = mw.Write(raw)
	if err := zw.Close(); err != nil {
		return err
	}
	return os.WriteFile(path, buf.Bytes(), 0o644)
}

func must(err error) {
	if err != nil {
		panic(err)
	}
}

func mustWrite(path string, data []byte) {
	must(os.WriteFile(path, data, 0o644))
}

func sha(data []byte) string {
	sum := sha256.Sum256(data)
	return hex.EncodeToString(sum[:])
}

func trim(s string, n int) string {
	s = strings.ReplaceAll(s, "\n", " ")
	if len(s) <= n {
		return s
	}
	return s[:n] + "…"
}
